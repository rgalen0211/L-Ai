"""Builds supabase/migrations/20261109000300_ask_locks.sql and its rollback from the repository's own migrations (CONNECT, 2026-11-09).

    py -I supabase/tests/build_ask_locks_migration.py --write      # writes both files
    py -I supabase/tests/build_ask_locks_migration.py              # prints whether the committed files are exactly what this builds

WHY A GENERATOR: the migration must hold the three FULL new function definitions (so what runs is in the file and can be read), and each must be exactly the repository's own definition plus ONE lock statement. Copying three long
bodies by hand could drift; this takes each body from the migration that created it, adds the lock, and writes the new text. supabase/tests/test_ask_locks.py rebuilds the files with this and fails if the committed ones differ,
and checks that each new body is the old body plus the lock and nothing else.
THE DRIFT CHECK (in the migration): before it replaces a live function it compares md5 of the live body (carriage returns removed) with the md5 of the repository's body. Equal: it replaces it. Already the new text: it leaves it
alone. Anything else: it stops with a plain sentence and changes nothing (the whole file is one transaction). A function that is not on the database is skipped.
"""
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MIG = ROOT / "supabase" / "migrations" / "20261109000300_ask_locks.sql"
RB = ROOT / "supabase" / "rollbacks" / "20261109000300_ask_locks_rollback.sql"
# name, the migration that created it, its argument types (for to_regprocedure)
FUNCS = [
    ("connect_forecast_ask", "20261104000500_forecast_requests.sql", "text, jsonb, integer, text, integer[], text"),
    ("connect_geo_ask", "20261104000300_geo_requests.sql", "text, double precision, double precision, integer, text[]"),
    ("connect_geo_ask_shape", "20261104000400_geo_questions.sql", "text, text, double precision, double precision, double precision, double precision, text, text"),
]
CLEANUP = "  delete from public.geo_requests where asked_at < now() - interval '7 days';\n"
LOCK = ("  -- One ask at a time per person: two asks in flight together would both count the same open requests and both insert (ask-locks migration, 2026-11-09). All three place-question asks share this one lock.\n"
        "  perform pg_advisory_xact_lock(hashtextextended('geo:' || me::text, 0));\n")


def md5(body):
    return hashlib.md5(body.replace("\r", "").encode("utf-8")).hexdigest()


def statement(name, src):
    t = (ROOT / "supabase" / "migrations" / src).read_text(encoding="utf-8").replace("\r\n", "\n")
    i = t.index(f"create function public.{name}(")
    j = t.index("\nend $$;", i) + len("\nend $$;")
    return t[i:j]


def body(stmt):
    return stmt[stmt.index("$$") + 2: stmt.rindex("$$")]


def locked(stmt):
    anchor = "\nbegin\n" + CLEANUP
    if stmt.count(anchor) != 1:
        raise SystemExit("the first lines of a function are not what this builder expects")
    return stmt.replace(anchor, "\nbegin\n" + LOCK + CLEANUP)


def pieces():
    out = []
    for name, src, args in FUNCS:
        old = statement(name, src)
        new = locked(old)
        out.append({"name": name, "src": src, "args": args, "old": old, "new": new, "old_md5": md5(body(old)), "new_md5": md5(body(new))})
    return out


def block(p, now, expect, already, expect_words, label):
    """One DO block: the drift check, then the replacement. `now` is the statement to run; `expect` the md5 the live body must have; `already` the md5 that means nothing to do."""
    sig = f"public.{p['name']}({p['args']})"
    stmt = now.replace("create function ", "create or replace function ", 1)
    return (f"-- {p['name']}: {label}\n"
            "do $do$\n"
            "declare cur text;\n"
            "begin\n"
            f"  select md5(replace(f.prosrc, chr(13), '')) into cur from pg_proc f where f.oid = to_regprocedure('{sig}');\n"
            f"  if cur is null then raise notice '{p['name']} is not on this database: skipped.'; return; end if;\n"
            f"  if cur = '{already}' then raise notice '{p['name']}: nothing to do (already in the wanted state).'; return; end if;\n"
            f"  if cur <> '{expect}' then\n"
            f"    raise exception 'The live function {p['name']} is not the one this change expects ({expect_words.replace(chr(39), chr(39) * 2)}); nothing was changed. Send this sentence to CONNECT.';\n"
            "  end if;\n"
            "  execute $fn$\n"
            f"{stmt}\n"
            "$fn$;\n"
            "end $do$;\n")


def build():
    ps = pieces()
    mig = (
        "-- ASK LOCKS (CONNECT, 2026-11-09; WORKER's finding 19:36, CC1's orders 19:37 and 20:50). NOT APPLIED: a PROPOSAL for CC1; Ryan applies it, and it CHANGES LIVE FUNCTIONS. GENERATED by supabase/tests/build_ask_locks_migration.py; do not edit by hand.\n"
        "-- The three place-question ask functions (connect_geo_ask 20261104000300, connect_geo_ask_shape 20261104000400, connect_forecast_ask 20261104000500) all count a person's open and today's requests in public.geo_requests and THEN\n"
        "-- insert, with nothing between. Two asks in flight together (an AI making parallel tool calls) each see 4 open and each insert: 6 open (the limit is 5); the 100-a-day count has the same gap.\n"
        "-- The fix: one advisory lock per person ('geo:' + the person's id), taken as the first statement of each function. A second ask waits until the first has committed, then counts it. Another person's ask is never held.\n"
        "-- Each function below is the repository's own definition (from the migration named) plus that one lock statement, in full, so what runs is what you read. BEFORE it replaces anything it compares the LIVE function's text (md5,\n"
        "-- carriage returns removed) with the repository's: equal, it replaces it; already the new text, it leaves it alone (safe to run twice); anything else (a drifted live function), it stops with a plain sentence and changes nothing\n"
        "-- (the whole file is one transaction). A function that is not on this database is skipped. Grants, owner and settings are kept (create or replace).\n"
        "-- What a person sees when two asks race at the limit: the first is accepted, the second is refused in words (\"There are already 5 place questions waiting for an answer. Wait for those first.\" or the 100-a-day sentence).\n"
        "-- Undo: supabase/rollbacks/20261109000300_ask_locks_rollback.sql. Check: see the last comment.\n"
        "\nbegin;\n\n"
        + "\n".join(block(p, p["new"], p["old_md5"], p["new_md5"], f"its text differs from the repository's {p['src']}", "adds the lock") for p in ps)
        + "\nselect ryagram_private.gate_apply();\n"
        "-- Check after running: select proname, position('pg_advisory_xact_lock' in pg_get_functiondef(oid)) > 0 as locked from pg_proc where pronamespace = 'public'::regnamespace and proname in ('connect_forecast_ask', 'connect_geo_ask', 'connect_geo_ask_shape') order by proname;  -- every row you get says true\n"
        "commit;\n")
    rb = (
        "-- ASK LOCKS: the exact undo of migrations/20261109000300_ask_locks.sql. GENERATED by supabase/tests/build_ask_locks_migration.py; NOT a migration: it lives outside migrations/ so nothing applies it by accident.\n"
        "-- It puts each function back to the repository's own definition (without the lock). Same drift check: a function whose text is neither the locked text nor the original stops it in words and changes nothing; no data is touched.\n"
        "-- After it, two asks in flight together can again pass the 5-open and 100-a-day limits.\n"
        "\nbegin;\n\n"
        + "\n".join(block(p, p["old"], p["new_md5"], p["old_md5"], "its text is neither the locked text nor the original of the repository", "takes the lock out") for p in ps)
        + "\ncommit;\n")
    return mig, rb, ps


if __name__ == "__main__":
    mig, rb, _ = build()
    if "--write" in sys.argv:
        MIG.write_text(mig, encoding="utf-8", newline="\n")
        RB.write_text(rb, encoding="utf-8", newline="\n")
        print("wrote", MIG.name, RB.name)
    else:
        same = MIG.read_text(encoding="utf-8").replace("\r\n", "\n") == mig and RB.read_text(encoding="utf-8").replace("\r\n", "\n") == rb
        print("the committed files are exactly what this builds" if same else "THE COMMITTED FILES DIFFER FROM WHAT THIS BUILDS")
        sys.exit(0 if same else 1)
