// "Usable" in the catalog means "on the INSTALLED worker's allowlist", and that list is a COMMITTED export (supabase/functions/_shared/worker_allowlist.txt, written from the
// worker's worker.toml by WORKER), never a machine-local read and never WORKER-SETUP.ps1's 23-id base list (BUILDER's finding, 2026-10-17: the catalog said 23, the worker runs 83).
// This file fails whenever the export and the two generated catalogs (public assets/app-catalog-data.js, server-only catalog_data.ts) disagree.
import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { CATALOG } from '../supabase/functions/_shared/catalog_data.ts';

const read = p => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
const plain = x => JSON.parse(JSON.stringify(x));
const text = read('supabase/functions/_shared/worker_allowlist.txt');
const lines = text.split('\n');
const ids = lines.filter(l => l.trim() && !l.startsWith('#')).map(l => l.trim().split(/\s+/)[0]);
const views = Object.fromEntries(lines.filter(l => l.startsWith('#views ')).map(l => l.split(/\s+/).slice(1)).map(([id, v]) => [id, v.split(',')]));
const declared = Number(/^# count: (\d+)$/m.exec(text)?.[1]);

const pub = (() => { const window = {}; vm.runInNewContext(read('assets/app-catalog-data.js'), { window }); return window.ryagramCatalogData; })();
const pubUsable = pub.entries.filter(e => e.status === 'usable').map(e => e.id).sort();
const srvUsable = CATALOG.filter(e => e.status === 'usable').map(e => e.id).sort();
const registry = new Set(pub.entries.map(e => e.id));

test('EXPORT: the committed allowlist is well formed: a "# count: N" header equal to its ids, no duplicates, and where it came from', () => {
  assert.ok(Number.isInteger(declared) && declared > 0, 'a "# count: N" header');
  assert.equal(ids.length, declared, `the header says ${declared} but the file lists ${ids.length}`);
  assert.equal(new Set(ids).size, ids.length, 'duplicate ids');
  assert.ok(ids.every(id => /^[a-z0-9_]{1,80}$/.test(id)), 'ids are dataset ids');
  assert.match(text, /^# worker\.toml \[datasets\]\.allow, engine [0-9a-f]{7,}, read \d{4}-\d{2}-\d{2} by WORKER/m);
});

test('COUNTS: the public catalog and the server catalog each have exactly as many usable datasets as the allowlist, and the SAME ones', () => {
  assert.equal(pubUsable.length, ids.length, `public catalog has ${pubUsable.length} usable, the allowlist ${ids.length}`);
  assert.equal(srvUsable.length, ids.length, `server catalog has ${srvUsable.length} usable, the allowlist ${ids.length}`);
  assert.deepEqual(plain(pubUsable), plain([...ids].sort()));
  assert.deepEqual(plain(srvUsable), plain(pubUsable));
  assert.deepEqual(plain([...pub.allow].sort()), plain([...ids].sort()), 'the public file\'s own allow list');
});

test('NOTHING STALE: every allowlisted id is in the catalog, no usable entry is off the allowlist, and nothing off it is "next" for a dataset that is already usable', () => {
  const missing = ids.filter(id => !registry.has(id));
  assert.deepEqual(plain(missing), [], `allowlisted but not in the catalog (stale export or a filtered dataset): ${missing.join(', ')}`);
  assert.deepEqual(plain(pubUsable.filter(id => !ids.includes(id))), []);
  for (const e of pub.entries) if (ids.includes(e.id)) assert.equal(e.status, 'usable', e.id);
  for (const e of pub.entries) if (!ids.includes(e.id)) assert.notEqual(e.status, 'usable', e.id);
});

test('VIEWS: a view restriction the worker enforces (#views) is what the catalog offers, in both catalogs', () => {
  assert.ok(Object.keys(views).length >= 1);
  for (const [id, vs] of Object.entries(views)) {
    assert.deepEqual(plain(CATALOG.find(e => e.id === id).film_types), plain(vs), `server catalog: ${id}`);
    assert.deepEqual(plain(pub.entries.find(e => e.id === id).views), plain(vs), `public catalog: ${id}`);
  }
});

test('SOURCE: the generator takes the allowlist from a FILE argument and no longer reads $AllowToml or any machine path for "usable"', () => {
  const gen = read('tools/gen-catalog.py');
  assert.match(gen, /--allowlist/);
  assert.doesNotMatch(gen.replace(/#.*$/gm, ''), /\$AllowToml|[A-Z]:[\/]/);
  assert.match(read('supabase/functions/_shared/catalog_data.ts'), /GENERATED by tools\/gen-catalog\.py/);
});

test('A DELIBERATE EDIT: dropping one id from the export would be caught (the counts and ids stop agreeing)', () => {
  const short = ids.slice(1);
  assert.notEqual(short.length, declared);
  assert.notEqual(pubUsable.length, short.length);
});
