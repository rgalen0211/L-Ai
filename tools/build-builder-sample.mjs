// Writes assets/app-builder-sample.js, the bundled sample the guided builder's tutorial walks through (#/build/sample, NEXT-BUILDER 38): ONE dataset's catalog entry and
// description, and the check of ONE request (the "Health" ready-made start), as the guided-builder function answers them in the test double (tests/fake-supabase.js).
// Nothing in the sample is decided by the page: it is a recording. tests/builder.test.mjs re-records it and fails when the file drifts.
//   node tools/build-builder-sample.mjs           write the file
//   node tools/build-builder-sample.mjs --print   print what would be written
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const { createFakeClient } = require('../tests/fake-supabase.js');
const read = p => fs.readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');

export async function recordSample() {
  const win = {};
  for (const f of ['app-builder.js', 'app-data.js']) vm.runInNewContext(read(`assets/${f}`), { window: win, setTimeout, clearTimeout });
  const B = win.ryagramBuilder, data = win.ryagramData(createFakeClient());
  const start = B.READY_MADE.find(r => r.id === 'health');
  const entry = (await data.builderCatalog()).datasets.find(d => d.id === start.dataset);
  const { dataset } = await data.builderDescribe(start.dataset);
  const request = B.requestFrom({ dataset: start.dataset, type: start.film_type, title: start.title, start: start.start, end: start.end });
  const compiled = await data.builderCompile(request);
  return publicOnly(JSON.parse(JSON.stringify({ start: start.id, entry, dataset, request, story: compiled.story, report: compiled.report })));
}

// The sample is a PUBLIC file, and the catalog's detail-only text (the full licence, method changes, known gaps, notes) is served only by the function, never shipped
// (tests/film-compile.test.mjs SERVER ONLY, MED-5). So the recording keeps the short licence and drops the rest; the sample says where the full text is.
export const SAMPLE_LICENCE = 'The full licence is shown when you choose this dataset with your own data.';
export function publicOnly(rec) {
  rec.dataset.licence = `${rec.dataset.licence_short}. ${SAMPLE_LICENCE}`;
  rec.dataset.methodology_breaks = [];
  rec.dataset.known_gaps = {};
  rec.report.method_notes = [];
  rec.report.warnings = rec.report.warnings.filter(w => !/method change/.test(w));
  rec.story.notes = `Dataset: ${rec.dataset.title} (${rec.dataset.id}). Source: ${rec.dataset.publisher}. Licence: ${rec.dataset.licence_short}.`;
  return rec;
}

export function sampleSource(sample) {
  return '// GENERATED by tools/build-builder-sample.mjs; do not edit by hand (tests/builder.test.mjs re-records it). The tutorial\'s bundled sample (#/build/sample, NEXT-BUILDER 38):\n'
    + '// one dataset and the check of one request, recorded from the guided-builder function\'s test double. Nothing here is a rule; the sample makes nothing.\n'
    + `window.ryagramBuilderSample = ${JSON.stringify(sample, null, 1)};\n`;
}

if ((process.argv[1] || '').endsWith('build-builder-sample.mjs')) {
  const src = sampleSource(await recordSample());
  if (process.argv.includes('--print')) process.stdout.write(src);
  else { fs.writeFileSync(new URL('../assets/app-builder-sample.js', import.meta.url), src); console.log('wrote assets/app-builder-sample.js'); }
}
