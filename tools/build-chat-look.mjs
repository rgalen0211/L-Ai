// ONE source for the look of the site and of the in-chat panels (Ryan 2026-11-20 12:35, "so chat and site can't drift").
// Reads WEB's design-system files, copies - by selector, never retyped - the :root tokens and the shared components (button, badge, focus ring, flip carousel) into
// supabase/functions/connect-core/chat_look.ts, together with the chat-only layout in tools/chat-look/chat-ui.css. The panels import that one file.
//
//   node tools/build-chat-look.mjs            write chat_look.ts
//   node tools/build-chat-look.mjs --check    exit 1 if chat_look.ts is not what the sources build (the DRIFT test), or if the layout breaks a rule below
//
// SOURCE: assets/ds.css + assets/ds-v11.css when the site has lifted them there (WEB's "Step 2"); until then the vendored copies in tools/chat-look/source/.
//   A test (tests/connect-chat-look.test.mjs) fails if both exist and differ, so a vendored copy cannot go stale unnoticed.
// RULES for chat-ui.css (checked here): it may use only var(--name) that the site's :root defines, and it writes no colour of its own (colours come from tokens;
//   color-mix() of a token is fine). The shared CSS carries no url(), no @import, no dashed or dotted border (the panels' pages are pinned to load nothing).
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'supabase/functions/connect-core/chat_look.ts');
const KEEP = [':root', '.btn', '.badge', '.flip', '.scroll-panel', ':focus-visible'];
const read = (p) => fs.readFileSync(p, 'utf8').replace(/\r\n/g, '\n');

export function sourceDir() {
  const site = path.join(ROOT, 'assets');
  return fs.existsSync(path.join(site, 'ds.css')) && fs.existsSync(path.join(site, 'ds-v11.css')) ? site : path.join(ROOT, 'tools/chat-look/source');
}

/** Top-level rules as text ('a{...}' and '@media(...){...}'), brace matched, comments dropped. */
export function rules(css) {
  css = css.replace(/\/\*[\s\S]*?\*\//g, '');
  const out = []; let depth = 0, start = 0;
  for (let i = 0; i < css.length; i++) {
    if (css[i] === '{') depth++;
    else if (css[i] === '}') { depth--; if (depth === 0) { out.push(css.slice(start, i + 1).trim()); start = i + 1; } }
  }
  return out.filter(Boolean);
}
function keep(rule) {
  const head = rule.slice(0, rule.indexOf('{')).trim();
  if (head.startsWith('@media')) { const inner = rules(rule.slice(rule.indexOf('{') + 1, rule.lastIndexOf('}'))); return inner.length > 0 && inner.every(keep); }
  return head.split(',').every((s) => KEEP.some((k) => s.trim().startsWith(k)));
}
/** Whitespace only: comments out, runs collapsed, no space after { ; , : or around } and before {; the last ; before } dropped. calc() and color-mix() keep the spaces they need. */
export function minify(css) {
  return css.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s+/g, ' ').replace(/ ?([{};]) ?/g, '$1').replace(/([,:]) /g, '$1').replace(/;}/g, '}').trim();
}


/** The rules for the chat-only layout (see the top): returns the problems, none when it is clean. Exported so a test can plant a fault. */
export function layoutProblems(ui, shared) {
  const problems = [];
  const css = ui.replace(/\/\*[\s\S]*?\*\//g, '');
  const names = new Set([...shared.matchAll(/(--[a-z0-9-]+)\s*:/g)].map((m) => m[1]));
  const used = new Set([...css.matchAll(/var\((--[a-z0-9-]+)/g)].map((m) => m[1]));
  const bad = [...used].filter((u) => !names.has(u));
  if (bad.length) problems.push('chat-ui.css uses tokens the site does not define: ' + bad.join(', '));
  const colours = css.match(/#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|hsla?\([^)]*\)/g);
  if (colours) problems.push('chat-ui.css writes a colour of its own (use a token): ' + [...new Set(colours)].slice(0, 8).join(' '));
  for (const [n, x] of [['the shared CSS', shared], ['chat-ui.css', ui]]) if (/url\(|@import|dashed|dotted/.test(x)) problems.push(n + ' has url(), @import, dashed or dotted (the panels load nothing and draw no dashed field)');
  return problems;
}

export function build() {
  const src = sourceDir();
  const files = ['ds.css', 'ds-v11.css'].map((n) => ({ n, t: read(path.join(src, n)) }));
  const picked = files.flatMap((f) => rules(f.t).filter(keep));
  const shared = picked.join('\n');
  const ui = read(path.join(ROOT, 'tools/chat-look/chat-ui.css'));
  const problems = layoutProblems(ui, shared);
  const names = new Set([...shared.matchAll(/(--[a-z0-9-]+)\s*:/g)].map((m) => m[1]));
  const sha = crypto.createHash('sha256').update(files.map((f) => f.n + '\n' + f.t).join('\n')).update(ui).digest('hex').slice(0, 16);
  const sharedMin = minify(shared), uiMin = minify(ui);
  const text = '// GENERATED by tools/build-chat-look.mjs from WEB\'s ds.css + ds-v11.css (the site\'s tokens and shared components) and tools/chat-look/chat-ui.css (the chat layout).\n' +
    '// DO NOT EDIT: change the source and run `node tools/build-chat-look.mjs`. tests/connect-chat-look.test.mjs fails if this file is not what the sources build.\n' +
    `export const CHAT_LOOK_SOURCE = ${JSON.stringify(sha)};\n` +
    `export const CHAT_SHARED_CSS = ${JSON.stringify(sharedMin)};\n` +
    `export const CHAT_UI_CSS = ${JSON.stringify(uiMin)};\n` +
    `export const CHAT_LOOK_TOKENS: readonly string[] = ${JSON.stringify([...names].sort())};\n`;
  return { text, problems, picked: picked.length, tokens: names.size, bytes: sharedMin.length + uiMin.length, src: path.relative(ROOT, src) };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const r = build();
  const check = process.argv.includes('--check');
  console.log(`source ${r.src}: ${r.picked} shared rules, ${r.tokens} tokens, ${r.bytes} bytes of CSS`);
  for (const p of r.problems) console.log('FAIL ' + p);
  if (r.problems.length) process.exit(1);
  if (check) {
    const have = fs.existsSync(OUT) ? read(OUT) : '';
    if (have !== r.text) { console.log('DRIFT: chat_look.ts is not what the sources build; run: node tools/build-chat-look.mjs'); process.exit(1); }
    console.log('chat_look.ts matches the sources');
  } else { fs.writeFileSync(OUT, r.text); console.log('wrote ' + path.relative(ROOT, OUT)); }
}
