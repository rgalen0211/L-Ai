// Builds the maker's standalone live editor (tools/maker-live/live.js and live.css) from the website's own files, so the PC's copy can not drift from the site's:
//   live.js  = the website's assets/app-editor-core.js, app-editor-progress.js, app-editor-draft.js, app-editor.js, then tools/maker-live/live-host.js
//   live.css = tools/maker-live/live-base.css, then assets/app-editor.css
//   node tools/build-maker-live.mjs            writes both        node tools/build-maker-live.mjs --check     exits 1 if the committed files differ
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = p => fs.readFileSync(path.join(root, p), 'utf8').replace(/\r\n/g, '\n');
const JS = ['assets/app-editor-core.js', 'assets/app-editor-progress.js', 'assets/app-editor-draft.js', 'assets/preview/text-layout.js', 'assets/app-editor.js', 'tools/maker-live/live-host.js'];
const CSS = ['tools/maker-live/live-base.css', 'assets/app-editor.css'];

export function build() {
  const js = '/* GENERATED by tools/build-maker-live.mjs from the website\'s own editor files; do not edit by hand. Sources, in order: ' + JS.join(', ') + ' */\n' + JS.map(f => `\n/* ---- ${f} ---- */\n${read(f)}`).join('');
  const css = '/* GENERATED by tools/build-maker-live.mjs; do not edit by hand. Sources, in order: ' + CSS.join(', ') + ' */\n' + CSS.map(f => `\n/* ---- ${f} ---- */\n${read(f)}`).join('');
  return { 'tools/maker-live/live.js': js, 'tools/maker-live/live.css': css };
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const out = build();
  let bad = false;
  for (const [f, text] of Object.entries(out)) {
    const file = path.join(root, f);
    if (process.argv.includes('--check')) {
      const have = fs.existsSync(file) ? fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
      if (have !== text) { console.error(`${f} is not what the generator writes`); bad = true; }
    } else { fs.writeFileSync(file, text); console.log('wrote', f); }
  }
  if (process.argv.includes('--check')) { if (bad) process.exit(1); console.log('ok'); }
}
