"""Test-coverage audit of the CONNECT connector (INTERNAL, CONNECT 2026-10-19). Read-only: it only reads files in the repo.

    py tools/connect_coverage_audit.py [--markdown FILE]

What it measures (and what it cannot):
  SQL functions   every function the connect migrations create; whether the SQL suite (supabase/tests/test_connect.py), the node tests or the proof tools name it,
                  how many MUTANTS (tests/connect_sql_mutants.py) break something inside it, how many REFUSAL SITES (`raise exception`) it has and how many of those are
                  (a) asserted by text in a test, (b) inside a mutant's changed text
  TypeScript      every tool, every route and every database call of the connector, and whether a node test names it, and whether a TS mutant (tests/connect_mutants.mjs)
                  touches its file
A refusal site is 'covered' if its message text is asserted in a test OR a mutant removes it. 'Named' is a weak signal (a name in a test file); the refusal-site
and mutant columns are the strong ones. The riskiest uncovered paths are the ones that decide who may do what: sign-in, token, grant, revocation, limits, writes."""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MIGS = sorted((ROOT / "supabase" / "migrations").glob("*connect*.sql"))
SQL_TEST = ROOT / "supabase" / "tests" / "test_connect.py"
SQL_MUT = ROOT / "tests" / "connect_sql_mutants.py"
TS_MUT = ROOT / "tests" / "connect_mutants.mjs"
NODE_TESTS = sorted((ROOT / "tests").glob("connect*.test.mjs"))
PROOF_TOOLS = sorted((ROOT / "tools").glob("connect_*.py")) + sorted((ROOT / "tools").glob("connect_*.mjs"))


def text(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace")


def sql_functions():
    """-> {name: (migration file, body text)}"""
    out = {}
    for mig in MIGS:
        t = text(mig)
        starts = [(m.start(), m.group(1)) for m in re.finditer(r"^create (?:or replace )?function ([a-z_.]+)\(", t, re.M)]
        for i, (pos, name) in enumerate(starts):
            end = starts[i + 1][0] if i + 1 < len(starts) else len(t)
            out[name] = (mig.name, t[pos:end])
    return out


def mutant_olds() -> list[tuple[str, str]]:
    """(mutant name, the text it changes) for every SQL mutant, read from the harness source."""
    src = text(SQL_MUT)
    m = re.search(r"MUTANTS = \[(.*?)\n\]\n", src, re.S)
    out = []
    if not m:
        return out
    ns: dict = {}
    try:
        exec("MUTANTS = [" + m.group(1) + "\n]", ns)                 # the list holds only string literals
        for name, old, _new in ns["MUTANTS"]:
            out.append((name, old))
    except Exception:                                               # noqa: BLE001
        pass
    return out


def raise_sites(body: str):
    """[(message prefix, errcode or '')] for every `raise exception '...'` in a function body."""
    sites = []
    for m in re.finditer(r"raise exception\s+'((?:[^']|'')*)'(?:\s+using\s+errcode\s*=\s*'([A-Z0-9]+)')?", body):
        sites.append((m.group(1).replace("''", "'"), m.group(2) or ""))
    return sites


def key_of(msg: str) -> str:
    """The part of a message a test would assert on: the code before ':' or the first 40 characters."""
    return msg.split(":")[0][:40] if re.match(r"[a-z_]+:", msg) else msg[:40]


def main():
    funcs = sql_functions()
    sqltest, node, tools, tsmut = text(SQL_TEST), "\n".join(text(p) for p in NODE_TESTS), "\n".join(text(p) for p in PROOF_TOOLS), text(TS_MUT)
    all_tests = sqltest + "\n" + node + "\n" + tools
    muts = mutant_olds()
    rows, uncovered_sites = [], []
    for name, (mig, body) in funcs.items():
        short = name.split(".")[-1]
        named = {"sql": short in sqltest, "node": short in node, "tools": short in tools}
        in_muts = [n for n, old in muts if old and old.strip() and old.strip()[:80] in body]
        sites = raise_sites(body)
        site_cov = []
        for msg, code in sites:
            k = key_of(msg)
            asserted = bool(k) and k in all_tests
            mutated = any(old.strip() and k and k in old for _, old in muts)
            site_cov.append((msg, code, asserted, mutated))
            if not asserted and not mutated:
                uncovered_sites.append((name, msg, code))
        rows.append((name, mig, named, len(in_muts), site_cov))

    out = []
    w = out.append
    w("# CONNECT connector: test-coverage audit (generated by tools/connect_coverage_audit.py)\n")
    w(f"SQL functions: {len(rows)} in {len(MIGS)} migration file(s); SQL mutants: {len(muts)}; node test files: {len(NODE_TESTS)}; refusal sites: {sum(len(r[4]) for r in rows)}.\n")
    w("## SQL functions\n")
    w("| function | named in SQL tests | node | proof tools | mutants inside | refusal sites | asserted | mutated | neither |")
    w("|---|---|---|---|---|---|---|---|---|")
    for name, mig, named, nm, sc in rows:
        a = sum(1 for s in sc if s[2])
        mu = sum(1 for s in sc if s[3])
        ne = sum(1 for s in sc if not s[2] and not s[3])
        w(f"| `{name}` | {'yes' if named['sql'] else 'NO'} | {'yes' if named['node'] else '-'} | {'yes' if named['tools'] else '-'} | {nm} | {len(sc)} | {a} | {mu} | {ne} |")
    w("\n## Refusal sites that no test asserts and no mutant removes\n")
    if uncovered_sites:
        w("| function | the refusal | code |\n|---|---|---|")
        for f, msg, code in uncovered_sites:
            w(f"| `{f}` | {msg[:110]} | {code} |")
    else:
        w("none")
    # TypeScript
    w("\n## TypeScript: tools, routes and database calls\n")
    tools_src = text(ROOT / "supabase/functions/connect-core/tools.ts")
    tool_names = re.findall(r'name: "([a-z_]+)", title:', tools_src)
    w("| tool | named in a node test | TS mutants touching tools.ts |\n|---|---|---|")
    ts_mut_tools = len(re.findall(r"tools\.ts", tsmut))
    for t in tool_names:
        w(f"| `{t}` | {'yes' if t in node else 'NO'} | {ts_mut_tools} (file level) |")
    oauth_src = text(ROOT / "supabase/functions/connect-core/oauth.ts")
    routes = re.findall(r'route === "(/[a-z]+)"', oauth_src)
    w("\n| OAuth route | named in a node test |\n|---|---|")
    for r in dict.fromkeys(routes):
        w(f"| `{r}` | {'yes' if r in node else 'NO'} |")
    db_src = text(ROOT / "supabase/functions/connect/db.ts")
    calls = re.findall(r'"(connect_[a-z_]+)"', db_src)
    w("\n| database call (connect/db.ts) | in the SQL migration | exercised by the SQL suite |\n|---|---|---|")
    for c in dict.fromkeys(calls):
        w(f"| `{c}` | {'yes' if ('public.' + c) in funcs else 'NO'} | {'yes' if c in sqltest else 'NO'} |")
    res = "\n".join(out)
    if "--markdown" in sys.argv:
        Path(sys.argv[sys.argv.index("--markdown") + 1]).write_text(res + "\n", encoding="utf-8")
    print(res)


if __name__ == "__main__":
    main()
