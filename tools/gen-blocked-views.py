"""Writes supabase/functions/_shared/blocked_views.ts from tools/data/engine-catalog-block-list-1123.json (ENGINE's v2 list of dataset+view pairs the engine fails: map, bars, paired, panel, shares).
The connector's dataset_info subtracts them from the views it tells an AI it may use. Run:  python tools/gen-blocked-views.py   (tests/connect-blocked-views.test.mjs fails if the two drift apart)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
data = json.loads((ROOT / "tools" / "data" / "engine-catalog-block-list-1123.json").read_text(encoding="utf-8"))
lines = ["// GENERATED by tools/gen-blocked-views.py from tools/data/engine-catalog-block-list-1123.json (ENGINE's v2 list). Do not edit by hand: tests/connect-blocked-views.test.mjs fails on drift.",
         "// The dataset+view pairs the engine is known to fail. dataset_info subtracts them from the views an AI is told it may use; a line view works for every dataset.",
         "export const BLOCKED_VIEWS: Record<string, string[]> = {"]
for k in sorted(data):
    lines.append(f"  {json.dumps(k)}: {json.dumps(sorted(data[k]))},")
lines.append("};")
(ROOT / "supabase" / "functions" / "_shared" / "blocked_views.ts").write_text("\n".join(lines) + "\n", encoding="utf-8")
print("ok", len(data), "datasets")
