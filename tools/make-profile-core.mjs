// Builds assets/profile-core.js: the ENGINE's profile rules, in plain JavaScript, for the browser (spec section 4, option a).
//
// The rules live in two TypeScript files the engine session generates and owns (supabase/functions/_shared/profile.ts and profile_data.ts). The editor must not
// carry a second, hand-written validator (it drifts), so this script strips the types from THE SAME FILES and wraps them as window.ryagramProfile.
// tests/profile-core.test.mjs rebuilds the output in memory and fails if the committed assets/profile-core.js is not exactly that, and replays the engine's own
// fixtures through it. The server's answer still counts: set_engine_profile is the backstop.
//
//     node tools/make-profile-core.mjs            writes assets/profile-core.js
import fs from 'node:fs';
import { createHash } from 'node:crypto';
import { stripTypeScriptTypes } from 'node:module';

const root = new URL('../', import.meta.url);
const read = p => fs.readFileSync(new URL(p, root), 'utf8').replace(/\r\n/g, '\n');

export function buildProfileCore() {
  const dataTs = read('supabase/functions/_shared/profile_data.ts');
  const profTs = read('supabase/functions/_shared/profile.ts');
  const strip = (src) => stripTypeScriptTypes(src, { mode: 'strip' }).replace(/^import [^\n]*\n/gm, '').replace(/^export (?=(const|let|class|function|async function) )/gm, '');
  const sha = createHash('sha256').update(dataTs).update('\0').update(profTs).digest('hex').slice(0, 16);
  const exportsList = ['MAX_PROFILE_BYTES', 'MAX_PROFILES_PER_USER', 'ProfileError', 'checkShape', 'checkColours', 'parseProfile', 'validateProfile', 'LOOK_PATHS', 'assertLookOnly',
    'applyProfile', 'listPresets', 'getPreset', 'forkPreset', 'profileSchema', 'PRESETS', 'PRESET_LIST', 'SAMPLE_STORY', 'SAMPLE_SHEET_PERIODS', 'SAMPLE_PERIODS', 'THEME_DEFAULTS', 'PROFILE_SCHEMA', 'BAR_RACE'];
  return `// GENERATED by tools/make-profile-core.mjs from the engine's supabase/functions/_shared/profile_data.ts and profile.ts (source ${sha}). Do not edit.
// The ENGINE's profile rules for the browser: the same shape and colour checks, presets and apply step the server uses.
(() => {
${strip(dataTs)}
${strip(profTs)}
window.ryagramProfile = { ${exportsList.join(', ')} };
})();
`;
}

if (import.meta.url === new URL(`file:///${process.argv[1].replace(/\\/g, '/')}`).href) {
  fs.writeFileSync(new URL('assets/profile-core.js', root), buildProfileCore());
  console.log('wrote assets/profile-core.js');
}
