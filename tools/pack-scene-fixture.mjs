// Packs a scene-bundle FOLDER (what the engine's exporter writes: scene.json.gz and fonts/*.woff2) into the one stored zip
// WORKER serves, and writes the base64 wrapper /app/?mock loads. Same packing as the worker: fixed names, fixed times.
//
//   node tools/pack-scene-fixture.mjs <bundle-folder>      -> tests/fixtures/scene-real.zip and scene-real.js
//
// The committed fixture is a REAL engine export of the engine's own synthetic `network_fixture` dataset (a made-up road network,
// 180 frames), made like this from a Ryagram checkout at the engine commit named in tests/fixtures/scene-real.PROVENANCE.txt:
//   python -m ryagram.preview.bundle story.json --out <folder>
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const out = path.join(here, '..', 'tests', 'fixtures');

function crc32(buf) { let c = ~0; for (const b of buf) { c ^= b; for (let k = 0; k < 8; k++) c = c & 1 ? (c >>> 1) ^ 0xedb88320 : c >>> 1; } return ~c >>> 0; }
// A zip with fixed times; `deflate` is for tests of the reader (the worker writes stored entries).
import zlib from 'node:zlib';
function zip(files, deflate = false) {
  const locals = [], centrals = []; let offset = 0;
  for (const [name, data] of files) {
    const nameBuf = Buffer.from(name);
    const stored = deflate ? zlib.deflateRawSync(data, { level: 9 }) : data;
    const method = deflate ? 8 : 0;
    const crc = crc32(data);
    const lh = Buffer.alloc(30); lh.writeUInt32LE(0x04034b50, 0); lh.writeUInt16LE(20, 4); lh.writeUInt16LE(0, 6); lh.writeUInt16LE(method, 8);
    lh.writeUInt16LE(0, 10); lh.writeUInt16LE(0x21, 12); lh.writeUInt32LE(crc, 14); lh.writeUInt32LE(stored.length, 18); lh.writeUInt32LE(data.length, 22);
    lh.writeUInt16LE(nameBuf.length, 26); lh.writeUInt16LE(0, 28);
    locals.push(lh, nameBuf, stored);
    const ch = Buffer.alloc(46); ch.writeUInt32LE(0x02014b50, 0); ch.writeUInt16LE(20, 4); ch.writeUInt16LE(20, 6); ch.writeUInt16LE(0, 8); ch.writeUInt16LE(method, 10);
    ch.writeUInt16LE(0, 12); ch.writeUInt16LE(0x21, 14); ch.writeUInt32LE(crc, 16); ch.writeUInt32LE(stored.length, 20); ch.writeUInt32LE(data.length, 24);
    ch.writeUInt16LE(nameBuf.length, 28); ch.writeUInt32LE(offset, 42);
    centrals.push(ch, nameBuf);
    offset += 30 + nameBuf.length + stored.length;
  }
  const cd = Buffer.concat(centrals);
  const end = Buffer.alloc(22); end.writeUInt32LE(0x06054b50, 0); end.writeUInt16LE(files.length, 8); end.writeUInt16LE(files.length, 10);
  end.writeUInt32LE(cd.length, 12); end.writeUInt32LE(offset, 16);
  return Buffer.concat([...locals, cd, end]);
}
export { zip, crc32 };

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(fileURLToPath(import.meta.url))) {
  const folder = process.argv[2];
  if (!folder) { console.error('usage: node tools/pack-scene-fixture.mjs <bundle-folder>'); process.exit(2); }
  const files = [['scene.json.gz', fs.readFileSync(path.join(folder, 'scene.json.gz'))]];
  for (const f of fs.readdirSync(path.join(folder, 'fonts')).sort()) files.push([`fonts/${f}`, fs.readFileSync(path.join(folder, 'fonts', f))]);
  const bytes = zip(files);
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'scene-real.zip'), bytes);
  fs.writeFileSync(path.join(out, 'scene-real.js'),
    `// GENERATED by tools/pack-scene-fixture.mjs: a real engine export of a synthetic network (zip, base64) for /app/?mock. Not real data.\nwindow.ryagramSceneFixtureB64 = '${bytes.toString('base64')}';\n`);
  console.log('scene-real.zip', bytes.length, 'bytes;', files.map(f => f[0]).join(', '));
}
