"""Why each dataset that is NOT usable on the installed worker is not, grouped by the fix that unlocks it.

    python tools/unusable-report.py --engine <engine checkout> --cache <cache dir> --json out.json --md out.md

The LIST comes from the catalog itself (supabase/functions/_shared/catalog_data.ts, generated by tools/gen-catalog.py
from the engine registry and WORKER-SETUP.ps1's allowlist): every entry whose status is not `usable`. So the list cannot
drift from the catalog. The REASON is measured, not guessed: for each one the engine's own fetch runs over its whole
window OFFLINE (every socket is refused) against the cache, in a child process with a time limit, and the outcome is
classified. A dataset's status in the catalog says what the worker's allowlist says; this says what stops it being added.

Classes (an outcome is one of):
  cache_complete   the engine read the whole window from the cache with no network: it only needs the worker's
                   measurement (if `later`) and an allowlist entry (a `next` dataset is already measured)
  needs_cache_write the fetch would have written into the cache (a file it has not built or downloaded yet)
  needs_download   the fetch tried the network: the cache does not hold what this dataset needs; the message says what
  needs_key        the fetch needs a credential from the environment (never read or written here)
  engine_error     the fetch failed for a reason that is not the network: an engine issue to look at
  timeout          the fetch did not finish in the time limit
The geography is probed too (does its shape file load offline?), once per geography id.

It never writes into the cache or the engine, never reads a credential, and sets every child's network off.
"""
import argparse
import json
import re
import subprocess
import sys
from collections import defaultdict
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOG = ROOT / 'supabase' / 'functions' / '_shared' / 'catalog_data.ts'

CHILD = r'''
import builtins, io, json, os, socket, sys, time
from pathlib import Path
engine, cache, did, start, end = sys.argv[1:6]
sys.path.insert(0, engine)
CACHE = os.path.normcase(os.path.abspath(cache))
def _blocked(*a, **k): raise OSError("network blocked by the probe (offline)")
socket.socket.connect = _blocked
socket.getaddrinfo = lambda *a, **k: (_ for _ in ()).throw(OSError("network blocked by the probe (offline)"))
# READ-ONLY on the cache: the probe must never create, change or rename a file under it. A fetch that needs to write
# (a cache miss that would download, or a derived file it would build) stops with "probe is read-only".
def _under(p):
    try: return os.path.normcase(os.path.abspath(os.fspath(p))).startswith(CACHE)
    except Exception: return False
_open = builtins.open
def _guard_open(f, mode="r", *a, **k):
    if isinstance(f, (str, bytes, os.PathLike)) and any(c in mode for c in "wax+") and _under(f):
        raise PermissionError("probe is read-only: would write " + os.fspath(f))
    return _open(f, mode, *a, **k)
builtins.open = _guard_open; io.open = _guard_open
for name in ("makedirs", "mkdir", "rename", "replace", "remove", "unlink", "rmdir"):
    real = getattr(os, name)
    def mk(real, name):
        def g(p, *a, **k):
            if _under(p): raise PermissionError("probe is read-only: would " + name + " " + os.fspath(p))
            return real(p, *a, **k)
        return g
    setattr(os, name, mk(real, name))
from ryagram.maprace import datasets as D
spec = D.get(did)
out = {"id": did, "geo": None}
areas = None
try:
    D.geographies_for_spec(spec.geography_id, Path(cache))          # the shape set is installed
    # The same areas the pipeline hands a fetch (pipeline.py around line 3056): none for a plain dataset, the national
    # county list, one state's counties, or the states.
    from ryagram.maprace import geometry as geo, geographies as geos
    gid = spec.geography_id
    if spec.entity_kind == "plain":
        areas = []
    elif gid in ("us_counties", "us_counties_ct2021", geos.FROZEN2010_ID):
        areas = geo.load_counties(Path(cache), insets=False, ct_old=(gid == "us_counties_ct2021"),
                                  inset_layout="beside", frozen2010=(gid == geos.FROZEN2010_ID))
    elif gid.endswith("_counties"):
        wanted = {c[:2] for c in geos.get(gid, Path(cache)).entity_names}
        areas = [c for c in geo.load_counties(Path(cache)) if c.fips[:2] in wanted]
    else:
        areas = geo.load_states(Path(cache), insets=False, inset_layout="beside")
    out["geo"] = "ok"
except BaseException as e:
    out["geo"] = "error: " + " ".join(str(e).split())[:200]
t = time.time()
try:
    spec.fetch(cache_dir=Path(cache), areas=areas, months=36, start=start or None, end=end or None, refresh=False, options=dict(spec.options or {}))
    out["outcome"] = "ok"
except BaseException as e:
    out["outcome"] = "error"; out["type"] = type(e).__name__; out["msg"] = " ".join(str(e).split())[:300]
out["seconds"] = round(time.time() - t, 1)
print(json.dumps(out))
'''


def load_catalog():
    text = CATALOG.read_text(encoding='utf-8')
    a = text.index('export const CATALOG: any[] = ') + len('export const CATALOG: any[] = ')
    b = text.index(';\n\n// The worker')
    return json.loads(text[a:b])


def classify(r):
    if r['outcome'] == 'ok':
        return 'cache_complete', 'the engine read its whole window from the cache with no network'
    msg = r.get('msg', '')
    if 'probe is read-only' in msg:
        return 'needs_cache_write', 'the engine would write to the cache (a download or a derived file it has not built): ' + msg
    if re.search(r'api[_ ]?key|credential|token|environment variable|not set', msg, re.I):
        return 'needs_key', msg
    if re.search(r'network blocked|could not reach|connection|urlopen|resolve|download|offline|http', msg, re.I):
        return 'needs_download', msg
    return 'engine_error', f"{r.get('type')}: {msg}"


def probe(args, e):
    start, end = (e['window'] or [e['period']['from'], e['period']['to'] or e['period']['from']])
    try:
        cp = subprocess.run([sys.executable, '-I', '-c', CHILD, args.engine, args.cache, e['id'], start, end],
                            capture_output=True, text=True, timeout=args.timeout)
        line = [x for x in cp.stdout.splitlines() if x.startswith('{')]
        if cp.returncode != 0 or not line:
            return {'id': e['id'], 'outcome': 'error', 'type': 'ChildFailed', 'msg': (cp.stderr or cp.stdout)[-300:].replace('\n', ' | '), 'geo': None, 'seconds': 0}
        return json.loads(line[-1])
    except subprocess.TimeoutExpired:
        return {'id': e['id'], 'outcome': 'timeout', 'geo': None, 'seconds': args.timeout}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--engine', required=True)
    ap.add_argument('--cache', required=True)
    ap.add_argument('--json', required=True)
    ap.add_argument('--md', default='')
    ap.add_argument('--only', default='', help='probe only these comma-separated ids')
    ap.add_argument('--timeout', type=int, default=300)
    ap.add_argument('--workers', type=int, default=3)
    args = ap.parse_args()
    cat = load_catalog()
    todo = [e for e in cat if e['status'] != 'usable']
    if args.only:
        want = set(args.only.split(','))
        todo = [e for e in todo if e['id'] in want]
    with ThreadPoolExecutor(args.workers) as ex:
        results = list(ex.map(lambda e: probe(args, e), todo))
    rows = []
    for e, r in zip(todo, results):
        cls, why = ('timeout', 'did not finish in the time limit') if r['outcome'] == 'timeout' else classify(r)
        rows.append({'id': e['id'], 'status': e['status'], 'family': e['family'] or e['group'], 'geography': e['geography']['id'],
                     'film_types': e['film_types'], 'class': cls, 'why': why, 'geo': r.get('geo'), 'seconds': r.get('seconds')})
    Path(args.json).write_text(json.dumps({'engine': args.engine, 'rows': rows}, indent=1), encoding='utf-8', newline='\n')
    groups = defaultdict(list)
    for r in rows:
        groups[(r['class'], r['status'], r['family'], r['geo'] if (r['geo'] or '').startswith('error') else 'ok')].append(r)
    if args.md:
        lines = ['# Unusable datasets, grouped by fix', '', f'{len(rows)} entries are not `usable`; measured offline against `{args.cache}`.', '']
        for (cls, status, fam, geo), rs in sorted(groups.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            lines.append(f'## {cls} / {status} / {fam} ({len(rs)})')
            lines.append(f'geography: {"loads offline" if geo == "ok" else geo}; example reason: {rs[0]["why"]}')
            lines.append('ids: ' + ', '.join(r['id'] for r in rs))
            lines.append('')
        Path(args.md).write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    counts = defaultdict(int)
    for r in rows:
        counts[(r['class'], r['status'])] += 1
    print(json.dumps({f'{k[0]}/{k[1]}': v for k, v in sorted(counts.items())}, indent=1))


if __name__ == '__main__':
    main()
