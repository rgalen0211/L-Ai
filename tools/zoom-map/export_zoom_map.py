"""Zoom map prototype data (GEO 11-27): the contiguous states and, one file per state, its counties, as same-origin page
script files (the app's CSP connect-src is Supabase only, so page data ships as .js, like tools/perfect-city).

Inputs, all already on disk and all US Census Bureau works (public domain, 17 U.S.C. 105):
  boundaries  cb_2024_us_state_20m, cb_2024_us_county_20m (Cartographic Boundary Files 2024, 1:20,000,000)
  values      co-est2024-alldata.csv (Vintage 2024 population estimates, July 1 2024: SUMLEV 040 states, 050 counties)
Geometry is projected once to US Albers equal-area (EPSG:5070) into a fixed 960 x 600 frame, then simplified
(Douglas-Peucker) and rounded. The counties of a state live in the SAME frame, so zooming is only a new viewBox.
Alaska (02), Hawaii (15) and Puerto Rico (72) are left out of this prototype (insets are ENGINE's work).
  py -I -B tools/zoom-map/export_zoom_map.py --geo C:/Users/Ryan/Ryagram-cache/geo --values C:/Users/Ryan/Ryagram-cache/co-est2024-alldata.csv
"""
import argparse
import csv
import json
import math
import pathlib

import shapefile
from pyproj import Transformer

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'assets' / 'zoom-map'
VERSION = '20261127zm1'          # the ?v= the page loads every data file with (tests/zoom-map.test.mjs checks they agree)
LEFT_OUT = {'02', '15', '72'}
W, H, PAD = 960, 600, 10
SOURCES = {
    'boundaries': 'US Census Bureau, 2024 Cartographic Boundary Files, states and counties, 1:20,000,000 (public domain)',
    'values': 'US Census Bureau, Vintage 2024 Population Estimates, total population on July 1, 2024 (co-est2024-alldata; public domain)',
    'calculated': 'Share of the state and the colour bands are calculated by Ryagram from those estimates.',
}
HEADER = '// GENERATED by tools/zoom-map/export_zoom_map.py: US Census Bureau data, public domain. Do not edit by hand.\n'


def rdp(pts, tol):
    if len(pts) < 3:
        return pts
    keep = [False] * len(pts)
    keep[0] = keep[-1] = True
    stack = [(0, len(pts) - 1)]
    while stack:
        a, b = stack.pop()
        (x1, y1), (x2, y2) = pts[a], pts[b]
        dx, dy = x2 - x1, y2 - y1
        n = math.hypot(dx, dy)
        best, bi = -1.0, -1
        for i in range(a + 1, b):
            x, y = pts[i]
            d = abs(dy * x - dx * y + x2 * y1 - y2 * x1) / n if n else math.hypot(x - x1, y - y1)
            if d > best:
                best, bi = d, i
        if best > tol and bi > 0:
            keep[bi] = True
            stack += [(a, bi), (bi, b)]
    return [p for p, k in zip(pts, keep) if k]


def area(r):
    return abs(sum(r[i][0] * r[i - 1][1] - r[i - 1][0] * r[i][1] for i in range(len(r)))) / 2


def rings_of(shp, fwd):
    out = []
    parts = list(shp.parts) + [len(shp.points)]
    for a, b in zip(parts[:-1], parts[1:]):
        xs, ys = fwd.transform([p[0] for p in shp.points[a:b]], [p[1] for p in shp.points[a:b]])
        out.append(list(zip(xs, ys)))
    return out


def path_d(rings, tol, dec, min_area):
    """Simplified rings as one SVG path string; tiny islands are dropped, but the largest ring always stays."""
    biggest = max(rings, key=area)
    parts = []
    for r in rings:
        if r is not biggest and area(r) < min_area:
            continue
        s = rdp(r, tol)
        if len(s) < 4:
            s = r if len(r) <= 12 else rdp(r, tol / 4)
        pts = [(round(x, dec), round(y, dec)) for x, y in s]
        pts = [p for i, p in enumerate(pts) if i == 0 or p != pts[i - 1]]
        if pts[0] == pts[-1]:
            pts = pts[:-1]
        if len(pts) < 3:
            continue
        fmt = (lambda v: f'{v:.{dec}f}'.rstrip('0').rstrip('.')) if dec else (lambda v: str(int(v)))
        parts.append('M' + 'L'.join(f'{fmt(x)},{fmt(y)}' for x, y in pts) + 'Z')
    return ''.join(parts)


def write_js(path, target, key, doc):
    body = json.dumps(doc, separators=(',', ':'), ensure_ascii=False)
    path.write_text(HEADER + f'(window.{target} = window.{target} || {{}})[{json.dumps(key)}] = {body};\n', encoding='utf-8', newline='\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--geo', required=True)
    ap.add_argument('--values', required=True)
    a = ap.parse_args()
    geo = pathlib.Path(a.geo)
    fwd = Transformer.from_crs('EPSG:4269', 'EPSG:5070', always_xy=True)

    pop_state, pop_county = {}, {}
    with open(a.values, newline='', encoding='latin-1') as f:
        for r in csv.DictReader(f):
            if r['SUMLEV'] == '040':
                pop_state[r['STATE']] = int(r['POPESTIMATE2024'])
            elif r['SUMLEV'] == '050':
                pop_county[r['STATE'] + r['COUNTY']] = int(r['POPESTIMATE2024'])

    st = shapefile.Reader(str(geo / 'cb_2024_us_state_20m' / 'cb_2024_us_state_20m'), encoding='utf-8')
    states = [(rec.as_dict(), rings_of(s, fwd)) for s, rec in zip(st.shapes(), st.records()) if rec['STATEFP'] not in LEFT_OUT]
    xs = [x for _, rs in states for r in rs for x, _ in r]
    ys = [y for _, rs in states for r in rs for _, y in r]
    x0, x1, y0, y1 = min(xs), max(xs), min(ys), max(ys)
    k = min((W - 2 * PAD) / (x1 - x0), (H - 2 * PAD) / (y1 - y0))
    ox, oy = (W - k * (x1 - x0)) / 2, (H - k * (y1 - y0)) / 2

    def frame(rings):
        return [[(ox + (x - x0) * k, oy + (y1 - y) * k) for x, y in r] for r in rings]

    co = shapefile.Reader(str(geo / 'cb_2024_us_county_20m' / 'cb_2024_us_county_20m'), encoding='utf-8')
    by_state = {}
    for s, rec in zip(co.shapes(), co.records()):
        by_state.setdefault(rec['STATEFP'], []).append((rec.as_dict(), s))

    OUT.mkdir(parents=True, exist_ok=True)
    index, missing = [], []
    for rec, rings in sorted(states, key=lambda t: t[0]['NAME']):
        fp = rec['STATEFP']
        rings = frame(rings)
        bx = [x for r in rings for x, _ in r]
        by = [y for r in rings for _, y in r]
        bbox = [round(min(bx), 2), round(min(by), 2), round(max(bx), 2), round(max(by), 2)]
        ext = max(bbox[2] - bbox[0], bbox[3] - bbox[1])
        counties = []
        dec = max(1, min(3, math.ceil(-math.log10(ext / 3000))))
        for crec, cs in sorted(by_state.get(fp, []), key=lambda t: t[0]['GEOID']):
            gid = crec['GEOID']
            if gid not in pop_county:
                missing.append(gid)
            counties.append({'id': gid, 'name': crec['NAMELSAD'], 'pop': pop_county.get(gid),
                             'd': path_d(frame(rings_of(cs, fwd)), ext / 1400, dec, (ext / 900) ** 2)})
        write_js(OUT / f'st-{fp}.js', 'ryagramZoomMapCounties', fp, {'id': fp, 'name': rec['NAME'], 'counties': counties})
        if fp not in pop_state:
            missing.append(fp)
        index.append({'id': fp, 'ab': rec['STUSPS'], 'name': rec['NAME'], 'pop': pop_state.get(fp), 'counties': len(counties),
                      'bbox': bbox, 'd': path_d(rings, 0.45, 1, 0.6)})
    write_js(OUT / 'states.js', 'ryagramZoomMapData', 'us', {
        'version': VERSION, 'width': W, 'height': H, 'projection': 'US Albers equal-area (EPSG:5070)',
        'value': {'name': 'Population', 'kind': 'estimated', 'date': 'July 1, 2024'}, 'sources': SOURCES,
        'leftOut': sorted(LEFT_OUT), 'states': index})
    print(f'states: {len(index)}  counties: {sum(s["counties"] for s in index)}  without a value: {missing or "none"}')
    print(f'states.js {(OUT / "states.js").stat().st_size} bytes; largest county file '
          f'{max((p.stat().st_size, p.name) for p in OUT.glob("st-*.js"))}')


if __name__ == '__main__':
    main()
